export const textW = (str, s) => str.length * 6 * s - s;
export function drawGlyphs(ctx, str, x, y, s, color) {
  ctx.fillStyle = color;
  for (const ch of str) {
    const g = FONT[ch];
    if (g) for (let r = 0; r < 7; r++) { const bits = g[r]; if (!bits) continue;
      for (let c = 0; c < 5; c++) if (bits & (16 >> c)) ctx.fillRect(x + c * s, y + r * s, s, s); }
    x += 6 * s;
  }
}
/* Draw `str` in the pixel font; returns its width. */
export function ptext(ctx, str, x, y, s, color, align = 'left', shadow = true) {
  str = String(str).toUpperCase();
  const w = textW(str, s);
  if (align === 'center') x -= w / 2; else if (align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  if (shadow) drawGlyphs(ctx, str, x + s, y + s, s, 'rgba(0,0,0,0.85)');
  drawGlyphs(ctx, str, x, y, s, color);
  return w;
}
export function wrapText(str, maxChars) {
  const out = []; let line = '';
  for (const word of str.split(' ')) {
    if ((line + ' ' + word).trim().length > maxChars) { out.push(line.trim()); line = word; } else line += ' ' + word;
  }
  if (line.trim()) out.push(line.trim());
  return out;
}
